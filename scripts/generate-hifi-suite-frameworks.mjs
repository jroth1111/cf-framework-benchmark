#!/usr/bin/env node
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadMatrix } from "../bench/src/config-v4.mjs";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const matrixPath = path.join(repoRoot, "bench", "framework-matrix.json");
const generatedPath = path.join(repoRoot, "packages", "bench-contract", "src", "hifi-suite-frameworks.generated.js");

export async function computeHifiSuiteFrameworks(matrixFile = matrixPath) {
  const matrix = await loadMatrix(matrixFile);
  return matrix.frameworks
    .filter((framework) => framework?.hifi?.enabled === true)
    .map((framework) => framework.name)
    .sort();
}

function renderModule(names) {
  const lines = [
    "// AUTO-GENERATED by scripts/generate-hifi-suite-frameworks.mjs.",
    "// Do not edit by hand. Source: bench/framework-matrix.json (frameworks[].hifi.enabled).",
    "// Regenerate via: pnpm build:hifi-frameworks. Drift is checked in CI by",
    "// scripts/test-hifi-suite-frameworks.mjs and the test-bench-contract gate.",
    "",
    "export const HIFI_SUITE_FRAMEWORKS = Object.freeze([",
    ...names.map((name) => `  ${JSON.stringify(name)},`),
    "]);",
    "",
  ];
  return lines.join("\n");
}

async function main() {
  const names = await computeHifiSuiteFrameworks();
  const next = renderModule(names);
  const checkOnly = process.argv.includes("--check");
  if (checkOnly) {
    let current;
    try {
      current = await fs.readFile(generatedPath, "utf8");
    } catch (err) {
      if (err?.code === "ENOENT") {
        console.error(`generate-hifi-suite-frameworks: ${path.relative(repoRoot, generatedPath)} is missing.`);
        process.exit(1);
      }
      throw err;
    }
    if (current !== next) {
      console.error(
        `generate-hifi-suite-frameworks: ${path.relative(repoRoot, generatedPath)} is stale relative to bench/framework-matrix.json. Run: pnpm build:hifi-frameworks`
      );
      process.exit(1);
    }
    console.log(`HIFI_SUITE_FRAMEWORKS in sync with matrix (${names.length} frameworks).`);
    return;
  }
  await fs.writeFile(generatedPath, next, "utf8");
  console.log(`Wrote ${path.relative(repoRoot, generatedPath)} (${names.length} frameworks).`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  await main();
}
